DROP DATABASE IF EXISTS shopdex;
CREATE DATABASE shopdex CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE shopdex;

CREATE TABLE categorias (
  id     INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE,
  icono  VARCHAR(8)
);

CREATE TABLE marcas (
  id     INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE,
  pais   VARCHAR(50)
);

CREATE TABLE productos (
  id           INT AUTO_INCREMENT PRIMARY KEY,
  nombre       VARCHAR(100) NOT NULL,
  precio       DECIMAL(7,2) NOT NULL,
  stock        INT NOT NULL DEFAULT 0,
  categoria_id INT NOT NULL,
  marca_id     INT NOT NULL,
  fecha_alta   DATE NOT NULL,
  FOREIGN KEY (categoria_id) REFERENCES categorias(id),
  FOREIGN KEY (marca_id) REFERENCES marcas(id)
);

CREATE TABLE clientes (
  id             INT AUTO_INCREMENT PRIMARY KEY,
  nombre         VARCHAR(50) NOT NULL,
  apellidos      VARCHAR(100) NOT NULL,
  email          VARCHAR(100) NOT NULL UNIQUE,
  ciudad         VARCHAR(50),
  fecha_registro DATE NOT NULL
);

CREATE TABLE pedidos (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  cliente_id INT NOT NULL,
  fecha      DATETIME NOT NULL,
  estado     ENUM('pendiente', 'enviado', 'entregado', 'cancelado') NOT NULL,
  FOREIGN KEY (cliente_id) REFERENCES clientes(id)
);

-- Cada fila es un producto dentro de un pedido.
-- precio_unitario es el precio al que se vendió, que puede no
-- coincidir con el precio actual del producto (rebajas).
CREATE TABLE lineas_pedido (
  pedido_id       INT,
  producto_id     INT,
  cantidad        INT NOT NULL,
  precio_unitario DECIMAL(7,2) NOT NULL,
  PRIMARY KEY (pedido_id, producto_id),
  FOREIGN KEY (pedido_id) REFERENCES pedidos(id),
  FOREIGN KEY (producto_id) REFERENCES productos(id)
);

CREATE TABLE valoraciones (
  id          INT AUTO_INCREMENT PRIMARY KEY,
  producto_id INT NOT NULL,
  cliente_id  INT NOT NULL,
  puntuacion  TINYINT NOT NULL CHECK (puntuacion BETWEEN 1 AND 5),
  comentario  VARCHAR(255),
  fecha       DATE NOT NULL,
  UNIQUE (producto_id, cliente_id),
  FOREIGN KEY (producto_id) REFERENCES productos(id),
  FOREIGN KEY (cliente_id) REFERENCES clientes(id)
);


